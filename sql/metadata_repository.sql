-- UC2 Metadata Repository

CREATE SCHEMA IF NOT EXISTS metadata;

-- 1. Table catalog
CREATE TABLE IF NOT EXISTS metadata.table_catalog (
    table_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_name VARCHAR(128) NOT NULL,
    table_name VARCHAR(128) NOT NULL,
    layer_name VARCHAR(32) NOT NULL,
    table_description TEXT,
    source_system VARCHAR(128),
    refresh_method VARCHAR(64),
    notes TEXT,
    last_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (schema_name, table_name)
);

-- 2. Column metadata
CREATE TABLE IF NOT EXISTS metadata.column_metadata (
    column_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_name VARCHAR(128) NOT NULL,
    table_name VARCHAR(128) NOT NULL,
    column_name VARCHAR(128) NOT NULL,
    ordinal_position INTEGER,
    data_type VARCHAR(128),
    is_nullable BOOLEAN,
    is_primary_key BOOLEAN DEFAULT FALSE,
    is_foreign_key BOOLEAN DEFAULT FALSE,
    referenced_table VARCHAR(257),
    referenced_column VARCHAR(128),
    is_business_key BOOLEAN DEFAULT FALSE,
    column_description TEXT,
    pii_classification VARCHAR(32) DEFAULT 'not_assessed',
    validation_rule TEXT,
    notes TEXT,
    UNIQUE (schema_name, table_name, column_name)
);

-- 3. Data lineage: source-to-target mappings
CREATE TABLE IF NOT EXISTS metadata.data_lineage (
    lineage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_schema VARCHAR(128) NOT NULL,
    source_table VARCHAR(128) NOT NULL,
    source_column VARCHAR(128),
    target_schema VARCHAR(128) NOT NULL,
    target_table VARCHAR(128) NOT NULL,
    target_column VARCHAR(128),
    transformation_name VARCHAR(256),
    transformation_rule TEXT,
    load_type VARCHAR(32) DEFAULT 'incremental',
    evidence_status VARCHAR(32) DEFAULT 'needs_verification',
    notes TEXT
);

-- 4. Validation report evidence
CREATE TABLE IF NOT EXISTS metadata.validation_results (
    validation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_name VARCHAR(256) NOT NULL,
    validation_category VARCHAR(64) NOT NULL,
    schema_name VARCHAR(128),
    table_name VARCHAR(128),
    sql_or_method TEXT,
    expected_result TEXT,
    actual_result TEXT,
    status VARCHAR(24) DEFAULT 'NOT_RUN',
    evidence_reference TEXT,
    executed_at TIMESTAMPTZ,
    executed_by VARCHAR(128),
    notes TEXT,
    CHECK (status IN ('PASS', 'FAIL', 'NOT_RUN', 'NEEDS_RECHECK'))
);

-- 5. Business glossary
CREATE TABLE IF NOT EXISTS metadata.business_glossary (
    term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_name VARCHAR(128) NOT NULL UNIQUE,
    definition TEXT NOT NULL,
    domain_name VARCHAR(128),
    related_table VARCHAR(257),
    related_column VARCHAR(128),
    notes TEXT
);

